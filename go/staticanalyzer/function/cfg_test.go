// TestBuildCFG tests the `buildCFG` function by comparing the CFGs generated explicitly by the function with the
// CFGs generated by the `ctrlflow` pass to ensure that the CFGs generated by the `buildCFG` function are correct.
func TestBuildCFG(t *testing.T) {
	t.Parallel()

	testdataPaths := []string{
		"testdata",
		_contrivedTestsDirPath,
	}

	for _, testdataPath := range testdataPaths {
		// Load packages explicitly to get the ASTs for computing the actual CFGs
		pkgs, err := loader.LoadAll(testdataPath, nil /* cdeps */)
		require.NoErrorf(t, err, "Failed to load packages: %v", err)
		require.Greaterf(t, len(pkgs), 0, "Expected at least one package to be loaded")

		// Check if there are any errors in the packages
		for _, pkg := range pkgs {
			require.Nilf(t, pkg.Errors, "Expected no errors in package '%s'. Error: %s", pkg.Name, pkg.Errors)
		}

		// Run the test analyzer to get the expected CFGs from the `analysis` pass
		testdataAbsPath, err := filepath.Abs(testdataPath)
		require.NoErrorf(t, err, "Failed to get absolute path of testdata: %v", err)
		r := analysistest.Run(t, testdataAbsPath, analyzer, "./...")

		// Fetch expected CFGs from all passes
		expectedCFGMap := make(map[token.Position]string)
		for _, result := range r {
			pass := result.Pass
			ctrlflowResult := pass.ResultOf[ctrlflow.Analyzer].(*ctrlflow.CFGs)
			for _, passFile := range pass.Files {
				ast.Inspect(passFile, func(node ast.Node) bool {
					switch n := node.(type) {
					case *ast.FuncDecl:
						expectedCFGStr := ctrlflowResult.FuncDecl(n).Format(pass.Fset)
						expectedCFGMap[pass.Fset.Position(n.Pos())] = expectedCFGStr
					case *ast.FuncLit:
						expectedCFGStr := ctrlflowResult.FuncLit(n).Format(pass.Fset)
						expectedCFGMap[pass.Fset.Position(n.Pos())] = expectedCFGStr
					}
					return true
				})
			}
		}
		require.Greaterf(t, len(expectedCFGMap), 0, "Expected at least one function declaration to be found in the pass")

		actualFuncSet := make(map[token.Position]bool)
		for _, pkg := range pkgs {
			for _, file := range pkg.Syntax {
				var funcNodes []ast.Node // Store *ast.FuncDecl and *ast.FuncLit nodes

				ast.Inspect(file, func(node ast.Node) bool {
					switch n := node.(type) {
					case *ast.FuncDecl, *ast.FuncLit:
						funcNodes = append(funcNodes, n)
					}
					return true
				})

				for _, f := range funcNodes {
					pos := pkg.Fset.Position(f.Pos())
					expectedCFGStr, ok := expectedCFGMap[pos]
					require.True(t, ok, "Function defined on L%d not found in pass", pkg.Fset.Position(f.Pos()).Line)

					cfgBuilder := &CFGBuilder{astContext: asthelper.New(pkgdeps.New(pkg, map[string]*packages.Package{pkg.PkgPath: pkg}), f), decl: f}
					actualCFG := cfgBuilder.buildCFG()
					actualFuncSet[pos] = true

					actualCFGStr := actualCFG.Format(pkg.Fset)
					require.Equal(t, expectedCFGStr, actualCFGStr, "CFG mismatch for function defined on L%d", pkg.Fset.Position(f.Pos()).Line)
				}
			}
		}
		require.ElementsMatchf(t, maps.Keys(expectedCFGMap), maps.Keys(actualFuncSet), "Function declarations mismatch between expected and actual CFGs")
	}
}

// TestBuildAndTransformCFG tests the BuildAndTransformCFG function for canonicalization with various inputs. We use `src1` and `src2` as semantically
// equivalent inputs to test the BuildAndTransformCFG function. We then compare the DFS traversal of the CFGs generated by the two inputs
// to ensure that they are equal, implying that CFGs were correctly canonicalized.
func TestBuildAndTransformCFG(t *testing.T) {
	tests := []struct {
		name string
		src1 string
		src2 string
	}{
		{
			name: "Canonicalize nil comparison -- swap successors",
			src1: `package main

				func foo(x *int) int {
					if x != nil {
						return *x
					}
					return -1
				}`,
			src2: `package main

				func foo(x *int) int {
					if x == nil {
						return -1
					}
					return *x
				}`,
		},
		{
			name: "Canonicalize nil comparison -- swap comparison order",
			src1: `package main

				func foo(x *int) int {
					if x == nil {
						return -1
					}
					return *x
				}`,
			src2: `package main

				func foo(x *int) int {
					if nil == x {
						return -1
					}
					return *x
				}`,
		},
		{
			name: "Canonicalize conditional -- swap successors",
			src1: `package main

				func foo(cond bool) int {
					if !cond {
						return -1
					}
					return 0
				}`,
			src2: `package main

				func foo(cond bool) int {
					if cond {
						return 0
					}
					return -1
				}`,
		},
		{
			name: "Canonicalize conditional -- && nesting",
			src1: `package main

				func foo(x, y *int) int {
					if x == nil {
						if y == nil {
							return -1
						}
					}
					return 0
				}
				`,
			src2: `package main

				func foo(x, y *int) int {
					if x == nil && y == nil {
						return -1
					}
					return 0
				}`,
		},
		{
			name: "Canonicalize conditional -- || nesting",
			src1: `package main

				func foo(x, y *int) int {
					if x == nil {
						return -1
					}
					if y == nil {
						return -1
					}
					return 0
				}
				`,
			src2: `package main

				func foo(x, y *int) int {
					if x == nil || y == nil {
						return -1
					}
					return 0
				}`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			pkg1, funcDecl1 := mockCFGInput(t, tt.src1)
			pkg2, funcDecl2 := mockCFGInput(t, tt.src2)

			resultCFG1 := BuildAndTransformCFG(asthelper.New(pkgdeps.New(pkg1, map[string]*packages.Package{pkg1.PkgPath: pkg1}), funcDecl1), funcDecl1)
			resultCFG2 := BuildAndTransformCFG(asthelper.New(pkgdeps.New(pkg2, map[string]*packages.Package{pkg2.PkgPath: pkg2}), funcDecl1), funcDecl2)

			var dfs1, dfs2 []string
			dfs(pkg1, resultCFG1, resultCFG1.Blocks[0], &dfs1)
			dfs(pkg2, resultCFG2, resultCFG2.Blocks[0], &dfs2)
			require.ElementsMatch(t, dfs1, dfs2)
		})
	}
}

// dfs performs a depth-first search on the CFG to extract the expressions in the nodes of the blocks, and stores them
// in the result slice. Note that `visited` nodes are typically skipped in cyclic graph traversal. However, we don't do that
// here since `canonicalization of the || nesting` modifies the conditional blocks to point to the same successor block.
// Foe example, the conditional block `if x == nil || y == nil { return -1 }`. Here block for `if x == nil` and `if y == nil`
// will point to the same successor block `return -1`. This means that the same block is visited multiple times. Hence, we
// don't skip the visited nodes in the DFS traversal. This is also the reason why we don't use test cases with loops for
// testing the BuildAndTransformCFG() function.
func dfs(pkg *packages.Package, g *cfg.CFG, block *cfg.Block, result *[]string) {
	for _, node := range block.Nodes {
		s, err := asthelper.FormatExpr(node, pkg.Fset)
		if err != nil || len(s) == 0 {
			continue
		}
		*result = append(*result, s)
	}

	for _, succ := range block.Succs {
		dfs(pkg, g, g.Blocks[succ.Index], result)
	}
}

func mockCFGInput(t *testing.T, funcSrc string) (*packages.Package, *ast.FuncDecl) {
	// Create a function declaration
	astFile, funcDecl, fset := mockFuncDecl(funcSrc)

	// Perform type-checking on the AST
	info, typesPkg := loadPackageAndTypeCheck(t, fset, astFile)

	// Convert the types.Package and types.Info into a *packages.Package for CFG
	pkg := &packages.Package{
		Fset:      fset,
		Syntax:    []*ast.File{astFile},
		Types:     typesPkg,
		TypesInfo: info,
	}

	return pkg, funcDecl
}

// mockFuncDecl creates a simple function declaration for testing purposes
func mockFuncDecl(src string) (*ast.File, *ast.FuncDecl, *token.FileSet) {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		panic(err)
	}

	for _, decl := range node.Decls {
		if funcDecl, ok := decl.(*ast.FuncDecl); ok {
			return node, funcDecl, fset
		}
	}
	return nil, nil, nil
}

// loadPackageAndTypeCheck performs type checking on the provided AST node
func loadPackageAndTypeCheck(t *testing.T, fset *token.FileSet, astFile *ast.File) (*types.Info, *types.Package) {
	info := &types.Info{
		Types:      make(map[ast.Expr]types.TypeAndValue),
		Defs:       make(map[*ast.Ident]types.Object),
		Uses:       make(map[*ast.Ident]types.Object),
		Implicits:  make(map[ast.Node]types.Object),
		Scopes:     make(map[ast.Node]*types.Scope),
		Selections: make(map[*ast.SelectorExpr]*types.Selection),
	}

	conf := &types.Config{
		Importer: importer.Default(), // Use the default importer for type resolution
	}
	pkg, err := conf.Check("main", fset, []*ast.File{astFile}, info)
	require.NoError(t, err)
	require.NotNil(t, pkg)
	require.NotNil(t, info)

	return info, pkg
}
