const _testsDirPath = "./testdata"

func TestSignatureToASTMap(t *testing.T) {
	pkgs, err := loader.LoadAll(_testsDirPath, nil /* cdeps */)
	require.NoError(t, err)
	require.Greaterf(t, len(pkgs), 0, "Expected at least one package to be loaded")
	signatureASTMap := SignatureToASTMap(pkgs)
	require.NotNil(t, signatureASTMap.StoA, "SignatureASTMap should not be nil")
	require.NotNil(t, signatureASTMap.AtoS, "SignatureASTMap should not be nil")

	// one.go: 2 functions, 1 funclit
	// two.go: 1 function, 0 funclit
	// three.go: 0 functions, 0 funclit
	// deadmethod.go: 1 function (Fetch), 1 funclit
	// Check if the map has valid entries
	require.Len(t, signatureASTMap.StoA, 6, "Expected 6 entries in the map")
	require.Len(t, signatureASTMap.AtoS, 6, "Expected 6 entries in the map")

	funcCount := 0
	funclitCount := 0
	othersCount := 0
	for sig, node := range signatureASTMap.StoA {
		assert.NotNil(t, sig, "Signature should not be nil")
		assert.NotNil(t, node, "AST Node should not be nil")
		// Ensure reverse mapping exists
		v, ok := signatureASTMap.AtoS[node]
		assert.True(t, ok, "Reverse map should contain the AST Node")
		assert.Equal(t, sig, v, "Reverse map should contain the correct Signature")
		// Count the number of functions and funclits
		switch node.(type) {
		case *ast.FuncDecl:
			funcCount++
		case *ast.FuncLit:
			funclitCount++
		default:
			othersCount++
		}
	}
	assert.Equal(t, 4, funcCount, "Expected 4 functions")
	assert.Equal(t, 2, funclitCount, "Expected 2 funclits")
	assert.Equal(t, 0, othersCount, "Expected 0 other types")
}

func TestSSAToASTMap(t *testing.T) {
	pkgs, err := loader.LoadAll(_testsDirPath, nil /* cdeps */)
	require.NoError(t, err)
	require.Greaterf(t, len(pkgs), 0, "Expected at least one package to be loaded")
	prog, ssaPkgs := ssautil.Packages(pkgs, ssa.InstantiateGenerics)
	prog.Build()
	require.Greaterf(t, len(ssaPkgs), 0, "Expected at least one SSA package to be generated")

	// Call the function under test
	ssaASTMap := SSAToASTMap(pkgs, ssaPkgs, prog)
	require.NotNil(t, ssaASTMap.StoA, "SSAASTMap should not be nil")
	require.NotNil(t, ssaASTMap.AtoS, "SSAASTMap should not be nil")

	// Expected mappings:
	// one.go: >3 SSA functions: main, funclit, and funclit.func1
	// two.go: >1 SSA function: Two
	// three.go: ignore. No SSA functions
	// Note, there can be many more SSA functions generated by the compiler.
	expectedSSAFunctions := map[string]struct{}{
		"one.main":      struct{}{},
		"one.funclit":   struct{}{},
		"one.funclit$1": struct{}{},
		"two.Two":       struct{}{},
	}

	assert.GreaterOrEqual(t, len(ssaASTMap.StoA), 4, "Expected 4 SSA function entries in the map")
	assert.GreaterOrEqual(t, len(ssaASTMap.AtoS), 4, "Expected 4 AST entries in the map")

	funcCount := 0
	funclitCount := 0
	othersCount := 0
	foundNames := make(map[string]struct{})
	for fn, node := range ssaASTMap.StoA {
		v, ok := ssaASTMap.AtoS[node]
		assert.True(t, ok, "Reverse map should contain the AST Node")
		assert.Same(t, fn, v, "Reverse map should contain the correct SSA Function")
		foundNames[fn.String()] = struct{}{}
		switch node.(type) {
		case *ast.FuncDecl:
			funcCount++
		case *ast.FuncLit:
			funclitCount++
		default:
			othersCount++
		}
	}

	assert.GreaterOrEqual(t, funcCount, 3, "Expected >=3 functions")
	assert.GreaterOrEqual(t, funclitCount, 1, "Expected >=1 funclit")

	for name := range expectedSSAFunctions {
		_, ok := foundNames[name]
		assert.True(t, ok, "Expected SSA function "+name+" not found")
	}
}

// TestSSAToASTMapDeadUnexportedMethod guards the fix for the IB/OB->SSA mapping
// failure: a method of an unexported type that is never constructed or called
// outside of test code is omitted by ssautil.AllFunctions, yet the AST-scanning
// finders still discover RPC calls inside it. SSAToASTMap must map such methods
// (and their nested function literals) so the lookup does not miss.
func TestSSAToASTMapDeadUnexportedMethod(t *testing.T) {
	pkgs, err := loader.LoadAll(_testsDirPath, nil /* cdeps */)
	require.NoError(t, err)
	require.Greaterf(t, len(pkgs), 0, "Expected at least one package to be loaded")
	prog, _ := ssautil.Packages(pkgs, ssa.InstantiateGenerics)
	prog.Build()

	// Locate the *ast.FuncDecl for the dead (*deadProvider).Fetch method and the
	// *ast.FuncLit nested inside it.
	var fetchDecl *ast.FuncDecl
	var fetchLit *ast.FuncLit
	for _, pkg := range pkgs {
		if pkg.Types == nil || pkg.Types.Path() != "deadmethod" {
			continue
		}
		for _, file := range pkg.Syntax {
			ast.Inspect(file, func(n ast.Node) bool {
				switch node := n.(type) {
				case *ast.FuncDecl:
					if node.Name.Name == "Fetch" {
						fetchDecl = node
					}
				case *ast.FuncLit:
					fetchLit = node
				}
				return true
			})
		}
	}
	require.NotNil(t, fetchDecl, "expected to find the Fetch FuncDecl in testdata")
	require.NotNil(t, fetchLit, "expected to find the FuncLit inside Fetch")

	// The dead method (and its nested literal) must still map to SSA.
	ssaASTMap := SSAToASTMap(pkgs, nil /* ssaPkgs unused */, prog)

	fetchFn, ok := ssaASTMap.AtoS[fetchDecl]
	require.True(t, ok, "AtoS should contain the dead method's FuncDecl")
	assert.Contains(t, fetchFn.String(), "deadProvider).Fetch",
		"FuncDecl should map to the dead method's SSA function")

	litFn, ok := ssaASTMap.AtoS[fetchLit]
	require.True(t, ok, "AtoS should contain the nested FuncLit of the dead method")
	assert.NotNil(t, litFn, "nested FuncLit should map to an SSA function")

	// Reverse mapping must stay consistent.
	assert.Equal(t, fetchDecl, ast.Node(ssaASTMap.StoA[fetchFn]),
		"StoA should map the dead method's SSA function back to its FuncDecl")
}

// goSDKBinDir returns the directory containing the real `go` binary. Under `bazel test`,
// runtime.GOROOT() points at a stripped-down stdlib-only tree with no `bin/go` (see
// https://github.com/bazel-contrib/rules_go/issues/2370). rules_go's go_test sets RUNFILES_DIR
// (or TEST_SRCDIR/TEST_WORKSPACE) pointing at the runfiles tree, where the go_sdk's real bin/go
// is reachable if declared as a `data` dep; outside Bazel, runtime.GOROOT() already has one.
func goSDKBinDir() string {
	runfilesRoot := os.Getenv("RUNFILES_DIR")
	if runfilesRoot == "" {
		runfilesRoot = os.Getenv("TEST_SRCDIR")
	}
	if runfilesRoot != "" {
		if goBin := filepath.Join(runfilesRoot, "go_sdk", "bin", "go"); fileExists(goBin) {
			return filepath.Dir(goBin)
		}
	}
	return filepath.Join(runtime.GOROOT(), "bin")
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

// loader.LoadAll shells out to `go list` via golang.org/x/tools/go/packages, which resolves the
// `go` binary via the process's PATH. Under bazel test sandboxing the inherited PATH won't
// contain a working `go`, so TestMain fixes it up before any test runs (see goSDKBinDir above).
func TestMain(m *testing.M) {
	goBin := goSDKBinDir()
	pathOverride := goBin + string(os.PathListSeparator) + os.Getenv("PATH")
	os.Setenv("PATH", pathOverride)
	if os.Getenv("GOCACHE") == "" {
		if dir, err := os.MkdirTemp("", "mapper-gocache"); err == nil {
			os.Setenv("GOCACHE", dir)
		}
	}
	os.Exit(m.Run())
}
